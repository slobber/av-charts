namespace AvCharts.Controls;

/// <summary>Which way round a <see cref="SeriesTable"/> puts its series.</summary>
public enum SeriesTableOrientation
{
    /// <summary>One column for each series, and one row for each record.</summary>
    SeriesAsColumns,

    /// <summary>One row for each series, and one column for each record.</summary>
    SeriesAsRows,
}
